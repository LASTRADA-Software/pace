/// The one place this executable's own build is read, plus the pure rendering over it.
///
/// `CurrentBuildConfiguration` is deliberately NOT inline: the macros below are a property of
/// the translation unit that tests them, so testing them here -- in a unit compiled into
/// `pace-bench` with `pace-bench`'s flags -- is what makes the answer a statement
/// about this binary. An inline function in a header would be instantiated in every including
/// unit and the linker would keep one of them, which is a different question.
///
/// Everything else here is pure: it takes a `BuildConfiguration` and returns text, so
/// `BuildBanner_test.cpp` can stage a build this host cannot produce.

#include "BuildBanner.hpp"

